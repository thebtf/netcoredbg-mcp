// Unicode 15.1 default case folding, derived from CPython 3.13.14.
// The table contains mappings that differ from isolated lowercase plus U+0130;
// all other scalars reuse Unicode15Lower's generated Unicode 15.1 mapping.
// Unicode data is distributed under the license in Unicode15Lower.cs.
internal static class Unicode15CaseFold
{
    internal static bool Equals(string left, string right)
    {
        if (string.Equals(left, right, StringComparison.Ordinal)) return true;
        var a = new Reader(left);
        var b = new Reader(right);
        while (true)
        {
            var hasA = a.MoveNext(out var leftScalar);
            var hasB = b.MoveNext(out var rightScalar);
            if (hasA != hasB) return false;
            if (!hasA) return true;
            if (leftScalar != rightScalar) return false;
        }
    }

    internal static string Fold(string value)
    {
        var outputLength = value.Length;
        var changed = false;
        for (var offset = 0; offset < value.Length;)
        {
            var start = offset;
            var scalar = Unicode15Lower.ReadScalar(value, ref offset);
            Map(scalar, out var first, out var second, out var third);
            if (first != scalar || second != 0 || third != 0)
            {
                changed = true;
                outputLength = checked(outputLength - (offset - start) + Width(first)
                    + (second == 0 ? 0 : Width(second)) + (third == 0 ? 0 : Width(third)));
            }
        }
        if (!changed) return value;
        return string.Create(outputLength, value, static (destination, source) =>
        {
            var reader = new Reader(source);
            var offset = 0;
            while (reader.MoveNext(out var scalar)) Unicode15Lower.WriteScalar(destination, ref offset, scalar);
        });
    }

    internal static int CompareCodePoints(string? left, string? right)
    {
        if (ReferenceEquals(left, right)) return 0;
        if (left is null) return -1;
        if (right is null) return 1;
        var leftOffset = 0;
        var rightOffset = 0;
        while (leftOffset < left.Length && rightOffset < right.Length)
        {
            var a = Unicode15Lower.ReadScalar(left, ref leftOffset);
            var b = Unicode15Lower.ReadScalar(right, ref rightOffset);
            if (a != b) return a.CompareTo(b);
        }
        return (left.Length - leftOffset).CompareTo(right.Length - rightOffset);
    }

    private static int Width(int scalar) => scalar > 0xFFFF ? 2 : 1;

    private static void Map(int scalar, out int first, out int second, out int third)
    {
        if (scalar < 0x80)
        {
            first = scalar is >= 'A' and <= 'Z' ? scalar + 0x20 : scalar;
            second = third = 0;
            return;
        }
        var mappings = ExceptionalMappings;
        var low = 0;
        var high = mappings.Length / 4 - 1;
        while (low <= high)
        {
            var middle = low + ((high - low) / 2);
            var index = middle * 4;
            if (scalar < mappings[index]) high = middle - 1;
            else if (scalar > mappings[index]) low = middle + 1;
            else
            {
                first = mappings[index + 1];
                second = mappings[index + 2];
                third = mappings[index + 3];
                return;
            }
        }
        first = Unicode15Lower.SimpleLowerScalar(scalar);
        second = third = 0;
    }

    private struct Reader(string value)
    {
        private int _offset;
        private int _second;
        private int _third;

        internal bool MoveNext(out int scalar)
        {
            if (_second != 0)
            {
                scalar = _second;
                _second = _third;
                _third = 0;
                return true;
            }
            if (_offset == value.Length)
            {
                scalar = 0;
                return false;
            }
            var source = Unicode15Lower.ReadScalar(value, ref _offset);
            Map(source, out scalar, out _second, out _third);
            return true;
        }
    }

